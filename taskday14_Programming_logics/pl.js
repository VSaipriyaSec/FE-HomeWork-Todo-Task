
console.log("Day 14 - Programming Logics");

// 1. If condition
let age = 20;

if (age >= 18) {
    console.log("1. You are eligible to vote.");
}

// 2. If-else condition
let number = 7;

if (number % 2 === 0) {
    console.log("2. The number is even.");
} else {
    console.log("2. The number is odd.");
}

// 3. If-else-if condition
let mark = 85;

if (mark >= 90) {
    console.log("3. Grade: A");
} else if (mark >= 80) {
    console.log("3. Grade: B");
} else if (mark >= 50) {
    console.log("3. Grade: C");
} else {
    console.log("3. Grade: Fail");
}
